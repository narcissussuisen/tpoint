from datetime import datetime, date, timezone, timedelta

CST = timezone(timedelta(hours=8))

#: 2026 年 A 股休市日（**只列非周末日**；落在周六/周日的休市日由 is_trading_day 的
#: `wd < 5` 周末规则兜住，无需重复登记）。
#:
#: 权威来源（2026-09-25 逐条核对）：
#:   上交所《关于上海证券交易所2026年部分节假日休市安排的通知》上证公告〔2025〕45号
#:     https://www.sse.com.cn/disclosure/announcement/general/c/c_20251222_10802507.shtml
#:   上交所《关于2026年中秋節、國慶節休市安排的公告》上证公告〔2026〕22号
#:     https://big5.sse.com.cn/disclosure/announcement/general/c/c_20260915_10832273.shtml
#:   深交所《关于2026年中秋节、国庆节休市安排的通知》(2026-09-17)
#:     https://www.szse.cn/disclosure/notice/t20260917_622911.html
#: 2026 年无"周末开市"的调休交易日 ⇒ 黑名单模式成立。
#:
#: 逐节官方区间 → 本表条目（括号内为周末日，由周末规则覆盖）：
#:   元旦 1/1(四)–1/3(六)  → 1/1, 1/2                  [1/3 六]
#:   春节 2/15(日)–2/23(一) → 2/16,2/17,2/18,2/19,2/20, 2/23   [2/21 六, 2/22 日]
#:   清明 4/4(六)–4/6(一)  → 4/6                       [4/4 六, 4/5 日]
#:   劳动 5/1(五)–5/5(二)  → 5/1, 5/4, 5/5             [5/2 六, 5/3 日]
#:   端午 6/19(五)–6/21(日) → 6/19                     [6/20 六, 6/21 日]
#:   中秋 9/25(五)–9/27(日) → 9/25                     [9/26 六, 9/27 日]
#:   国庆 10/1(四)–10/7(三) → 10/1,10/2, 10/5,10/6,10/7 [10/3 六, 10/4 日]
#:   ⚠️ 官方公告另注明 1/4(日)、2/14(六)、2/28(六)、5/9(六)、9/20(日)、10/10(六) 为周末休市
#:      —— 均为周末，已由周末规则覆盖，故不列入本表。
#:   ⚠️ 9/28(一)、9/29(二)、9/30(三) 官方口径为**照常开市（交易日）**，不在此表内。
HOLIDAYS_2026 = frozenset({
    '2026-01-01', '2026-01-02',                                        # 元旦
    '2026-02-16', '2026-02-17', '2026-02-18', '2026-02-19',            # 春节
    '2026-02-20', '2026-02-23',
    '2026-04-06',                                                      # 清明
    '2026-05-01', '2026-05-04', '2026-05-05',                          # 劳动节
    '2026-06-19',                                                      # 端午
    '2026-09-25',                                                      # 中秋
    '2026-10-01', '2026-10-02', '2026-10-05', '2026-10-06', '2026-10-07',  # 国庆
})
HOLIDAYS = HOLIDAYS_2026          # 兼容别名


def is_trading_day(d) -> bool:
    """交易日判定（周一~周五 且 不在休市表）。接受 date / datetime / 'YYYY-MM-DD'。

    ⚠️ 与旧的三处内联实现语义完全一致（同样的周末规则 + 同样的休市集合）；
    唯一差异是**统一按 CST 取当前时间**（旧 alert_engine 用 naive local，本机为 CST 故等价，
    但显式带时区更不易在跨时区/容器环境里出错）。
    """
    if isinstance(d, str):
        s = d[:10]
        wd = datetime.strptime(s, '%Y-%m-%d').weekday()
    elif isinstance(d, datetime):
        s, wd = d.strftime('%Y-%m-%d'), d.weekday()
    elif isinstance(d, date):
        s, wd = d.strftime('%Y-%m-%d'), d.weekday()
    else:
        raise TypeError('is_trading_day 需要 date/datetime/str，得到 %r' % type(d))
    return wd < 5 and s not in HOLIDAYS


def is_trading_today(now=None) -> bool:
    """今天是否交易日。now 可显式传入（便于测试）。"""
    return is_trading_day(now or datetime.now(CST))
